def _api_get(access_token: str, path: str, params: dict | None = None):
    r = requests.get(
        API_BASE + path,
        headers={"Authorization": f"Bearer {access_token}"},
        params=params or {},
        timeout=20,
    )
    if not r.ok:
        try:
            detail = r.json()
        except Exception:
            detail = r.text
        raise HTTPException(
            status_code=r.status_code,
            detail={"spotify": detail, "path": path, "params": params},
        )
    return r.json()

def _api_post(
    access_token: str,
    path: str,
    json_body: dict | None = None,
    params: dict | None = None,
):
    r = requests.post(
        API_BASE + path,
        headers={
            "Authorization": f"Bearer {access_token}",
            "Content-Type": "application/json",
        },
        params=params or {},
        json=json_body or {},
        timeout=20,
    )
    if not r.ok:
        try:
            detail = r.json()
        except Exception:
            detail = r.text
        raise HTTPException(
            status_code=r.status_code,
            detail={"spotify": detail, "path": path, "json": json_body},
        )
    return r.json() if r.text else {}

def create_playlist_with_tracks(access_token: str, user_id: str, name: str, uris: list[str]) -> dict:
    # 1) create playlist (private by default; flip to True if you want public)
    pl = _api_post(
        access_token,
        f"/users/{user_id}/playlists",
        json_body={
            "name": name,
            "public": True,
            "description": "Generated by MoodPlaylists",
        },
    )
    # 2) add tracks in chunks of 100 (Spotify limit per request)
    if uris:
        for i in range(0, len(uris), 100):
            _api_post(
                access_token,
                f"/playlists/{pl['id']}/tracks",
                json_body={"uris": uris[i:i+100]},
            )
    return pl

def _refresh_token(refresh_token: str) -> dict:
    r = requests.post(
        TOKEN_URL,
        data={
            "grant_type": "refresh_token",
            "refresh_token": refresh_token,
            "client_id": CLIENT_ID,
            "client_secret": CLIENT_SECRET,
        },
        timeout=20,
    )
    r.raise_for_status()
    return r.json()


def _ensure_token(user_id: str) -> str:
    store = _load_tokens()
    t = store.get(user_id)
    if not t:
        raise HTTPException(status_code=401, detail="No token for user. Login again.")
    if _now() < int(t.get("expires_at", 0)) - 15:
        return t["access_token"]

    # Need refresh
    if not t.get("refresh_token"):
        raise HTTPException(status_code=401, detail="No refresh token. Login again.")
    data = _refresh_token(t["refresh_token"])
    access_token = data["access_token"]
    expires_at = _now() + int(data.get("expires_in", 3600))
    # Spotify may not return refresh_token on refresh; keep the old one
    t["access_token"] = access_token
    t["expires_at"] = expires_at
    _save_tokens(store)
    return access_token


