MOOD_PRESETS: Dict[str, Dict[str, float]] = {
    "happy": {
        "min_valence": 0.6,
        "max_valence": 1.0,
        "min_energy": 0.5,
        "max_energy": 1.0,
        "min_danceability": 0.5,
    },
    "chill": {
        "min_valence": 0.3,
        "max_valence": 0.8,
        "max_energy": 0.6,
        "min_acousticness": 0.2,
    },
    "focus": {
        "max_valence": 0.6,
        "max_energy": 0.6,
        "min_instrumentalness": 0.4,
        "max_speechiness": 0.5,
    },
    "workout": {
        "min_energy": 0.7,
        "min_danceability": 0.6,
        "min_tempo": 110,  # let tempo help without forcing a “target”
    },
    "melancholic": {
        "max_valence": 0.4,
        "min_acousticness": 0.3,
    },
}

# === Fallback helpers (place ABOVE build_recommendations) ===
def _get_audio_features(access_token: str, track_ids: list[str]) -> dict[str, dict]:
    """Return {track_id: features} for up to 100 ids per call."""
    feats: dict[str, dict] = {}
    if not track_ids:
        return feats
    chunk = 100
    for i in range(0, len(track_ids), chunk):
        ids = ",".join(track_ids[i:i+chunk])
        r = _api_get(access_token, "/audio-features", {"ids": ids})
        for f in r.get("audio_features", []) or []:
            if f:
                feats[f["id"]] = f
    return feats

def _within_preset(features: dict, preset: dict) -> bool:
    """Check if audio features satisfy min_/max_ bounds in a mood preset."""
    for k, v in preset.items():
        if k.startswith("min_"):
            metric = k[4:]
            if features.get(metric) is None or features[metric] < v:
                return False
        elif k.startswith("max_"):
            metric = k[4:]
            if features.get(metric) is None or features[metric] > v:
                return False
        # ignore target_* keys
    return True


def _fallback_from_top_tracks(access_token: str, preset: dict, limit: int = 20) -> list[dict]:
    """Use user's top tracks and filter by mood preset."""
    try:
        top = _api_get(access_token, "/me/top/tracks", {"limit": 50})
        items = top.get("items") or []
        if not items:
            return []
        ids = [t.get("id") for t in items if t.get("id")]
        feats = _get_audio_features(access_token, ids)

        matched: list[dict] = []
        for t in items:
            fid = t.get("id")
            if not fid:
                continue
            if _within_preset(feats.get(fid, {}), preset):
                matched.append(t)
                if len(matched) >= limit:
                    break
        return matched or items[:limit]
    except Exception:
        return []


def _fallback_from_genre_playlist(
    access_token: str, genre: str, preset: dict, limit: int = 20
) -> list[dict]:
    """Search public playlists by a genre term and filter their tracks by mood preset.
       If nothing matches, return some items anyway so we never end empty."""
    try:
        q = (genre or "").strip()
        if not q:
            return []

        search = _api_get(access_token, "/search", {
            "q": q, "type": "playlist", "limit": 5, "market": "from_token"
        })
        playlists = ((search.get("playlists") or {}).get("items") or [])
        if not playlists:
            return []

        first_nonempty_items: list[dict] = []

        for pl in playlists:
            pid = pl["id"]
            pl_tracks = _api_get(access_token, f"/playlists/{pid}/tracks", {
                "limit": 100, "market": "from_token"
            })
            items = [it.get("track") for it in (pl_tracks.get("items") or []) if it.get("track")]
            if items and not first_nonempty_items:
                first_nonempty_items = items  # keep something to return

            ids = [t.get("id") for t in items if t and t.get("id")]
            feats = _get_audio_features(access_token, ids)

            matched: list[dict] = []
            for t in items:
                fid = t.get("id")
                if fid and _within_preset(feats.get(fid, {}), preset):
                    matched.append(t)
                    if len(matched) >= limit:
                        break

            if matched:
                return matched[:limit]

        # no matches across candidates → return some items anyway
        return first_nonempty_items[:limit]
    except Exception:
        return []

