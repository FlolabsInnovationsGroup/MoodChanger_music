@app.get("/login")
def login():
    state = secrets.token_urlsafe(16)
    params = {
        "client_id": CLIENT_ID,
        "response_type": "code",
        "redirect_uri": REDIRECT_URI,
        "scope": " ".join(
            ["user-top-read", "playlist-modify-public", "playlist-modify-private"]
        ),
        "state": state,
        "show_dialog": "false",
    }
    resp = RedirectResponse(AUTH_URL + "?" + urlencode(params))
    resp.set_cookie("state", signer.dumps(state), httponly=True, samesite="lax")
    return resp


@app.get("/callback")
def callback(request: Request, code: str | None = None, state: str | None = None):
    # validate state
    cookie_state = request.cookies.get("state")
    expected = signer.loads(cookie_state) if cookie_state else None
    if not expected or state != expected:
        return JSONResponse(
            {"stage": "state_check", "error": "state_mismatch"}, status_code=400
        )

    # exchange code -> tokens (send client creds in BODY)
    r = requests.post(
        TOKEN_URL,
        data={
            "grant_type": "authorization_code",
            "code": code,
            "redirect_uri": REDIRECT_URI,
            "client_id": CLIENT_ID,
            "client_secret": CLIENT_SECRET,
        },
        timeout=20,
    )
    if r.status_code != 200:
        return JSONResponse(
            {
                "stage": "auth_code_exchange",
                "status": r.status_code,
                "body": r.text,
                "redirect_used": REDIRECT_URI,
            },
            status_code=500,
        )

    tok = r.json()
    access_token = tok["access_token"]
    refresh_token = tok.get("refresh_token")
    expires_at = _now() + int(tok.get("expires_in", 3600))

    me = _api_get(access_token, "/me")
    user_id = me["id"]

    store = _load_tokens()
    store[user_id] = {
        "access_token": access_token,
        "refresh_token": refresh_token,
        "expires_at": expires_at,
    }
    _save_tokens(store)

    resp = RedirectResponse(url="/static/app.html")
    resp.set_cookie("user", signer.dumps(user_id), httponly=True, samesite="lax")
    return resp


@app.get("/logout")
def logout():
    resp = RedirectResponse(url="/")
    resp.delete_cookie("user")
    resp.delete_cookie("state")
    return resp


